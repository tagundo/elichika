"""Clone source verification keeps every proof with one read-only handle per DB.

All databases, receipts and native bundles here are generated by existing
fixtures; these checks never read a real installation or game account.
"""
from collections import Counter
from contextlib import closing
import json
from pathlib import Path
import sqlite3
import unittest
from unittest.mock import patch

import costume_management as management
import costume_scene_clones as canonical
import costume_scene_installer as installer
import test_costume_scene_clones as clone_fixtures
import test_costume_scene_installer as installer_fixtures


class SourceConnectionChecks:
    file_error = ValueError

    def capture_connections(self, *, fail_on=None):
        original = management._connect
        self.connections = []
        self.opened = Counter()

        def connect(root, relative, *args, **kwargs):
            self.opened[relative] += 1
            self.assertFalse(kwargs.get("writable", False))
            if fail_on and sum(self.opened.values()) == fail_on:
                raise sqlite3.OperationalError("injected read-only open failure")
            db = original(root, relative, *args, **kwargs)
            self.connections.append(db)
            return db

        return patch.object(management, "_connect", side_effect=connect)

    def assert_all_closed(self):
        self.assertTrue(self.connections)
        for db in self.connections:
            with self.assertRaises(sqlite3.ProgrammingError):
                db.execute("SELECT 1")

    def test_one_connection_per_database_still_checks_every_owned_row(self):
        with self.capture_connections(), patch.object(
                management, "_selected", wraps=management._selected) as selected:
            info = self.verify()
        self.assertEqual(info["suit_id"], self.suit_id)
        self.assertEqual(selected.call_count, len(self.receipt["owned_rows"]))
        self.assertTrue(all(count == 1 for count in self.opened.values()))
        self.assertEqual(set(self.opened), {row["db"] for row in self.receipt["owned_rows"]})
        self.assert_all_closed()

    def test_next_call_rechecks_a_late_owned_row_instead_of_caching_success(self):
        self.verify()
        item = next(row for row in reversed(self.receipt["owned_rows"])
                    if any(key not in row["key"] and value is not None
                           for key, value in row["row"].items()))
        column = next(key for key, value in item["row"].items()
                      if key not in item["key"] and value is not None)
        previous = item["row"][column]
        changed = previous + 1 if isinstance(previous, (int, float)) else str(previous) + "-changed"
        where, values = management._where(item["key"])
        with closing(sqlite3.connect(self.fixture.root / item["db"])) as db:
            db.execute("UPDATE " + management._q(item["table"]) + " SET " + management._q(column)
                       + "=? WHERE " + where, [changed, *values])
            db.commit()
        with self.capture_connections(), self.assertRaisesRegex(ValueError, self.row_error):
            self.verify()
        self.assertTrue(all(count == 1 for count in self.opened.values()))
        self.assert_all_closed()

    def test_file_hash_failure_closes_every_reused_connection(self):
        self.verify()
        path = Path(self.receipt["owned_files"][0]["path"])
        data = bytearray(path.read_bytes())
        data[-1] ^= 1
        path.write_bytes(data)
        with self.capture_connections(), self.assertRaises(self.file_error):
            self.verify()
        self.assertTrue(all(count == 1 for count in self.opened.values()))
        self.assert_all_closed()

    def test_later_open_failure_closes_previous_database(self):
        with self.capture_connections(fail_on=2), self.assertRaisesRegex(
                sqlite3.OperationalError, "injected read-only open failure"):
            self.verify()
        self.assertEqual(sum(self.opened.values()), 2)
        self.assertEqual(len(self.connections), 1)
        self.assert_all_closed()


class SceneSourceConnectionTests(SourceConnectionChecks, unittest.TestCase):
    row_error = "installed scene costume changed"

    def setUp(self):
        self.fixture = installer_fixtures.SceneInstallerTests("runTest")
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        installed = self.fixture.install()
        self.suit_id = installed["suit_id"]
        self.receipt = json.loads(Path(installed["receipt_path"]).read_text())

    def verify(self):
        return installer.installed_scene_source(self.suit_id, root=self.fixture.root)


class CanonicalSourceConnectionTests(SourceConnectionChecks, unittest.TestCase):
    row_error = "installed database rows changed"
    file_error = management.ManagementError

    def setUp(self):
        self.fixture = clone_fixtures.CanonicalCloneTests("runTest")
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        source = self.fixture.source()
        self.suit_id = self.fixture.clone_source(source, bare=True)
        self.receipt = self.fixture.receipt(self.suit_id)

    def verify(self):
        return canonical.resolve_canonical_clone_source(self.suit_id, root=self.fixture.root)


